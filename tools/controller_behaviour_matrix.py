#!/usr/bin/env python3
"""What every controller input actually does, screen by screen.

This resolves each panel's event handler to the engine functions it calls, so a
row says what a button *does* rather than which event id it delivers. An event
arriving proves the wiring; it does not prove the screen responds, and those are
different claims.

Three sources are joined:

  reverse-engineering/retained-gui-event-inventory.txt
        every panel, its dispatcher, and the handler address for each event it
        implements. Regenerated by tools/map_retained_gui_events.py.

  the executable
        each handler is disassembled to the first return and its call targets
        collected, which is what turns "event 0x35 is implemented" into
        "calls CGuiInGame::PrevSWInGameGui".

  build/research/.../kotor1_0_3.db
        function names for those call targets.

The KMRP side -- which physical button sends which event, and which screens the
spatial navigation layer drives -- is declared below and must match
src/controller-native/K1NativeJoystick.cpp. The test suite checks the bindings
live; this file is the reference for what they mean.

Nothing here touches the game. It is a static pass whose output is then checked
against the running game by testing/controller/audit_screen_behaviour.py.

Documentation standard: see `docs/documentation-standard.md`.
"""

